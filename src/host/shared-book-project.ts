/** A shared project contains published/domain history, never an executable task
 * checkpoint. Source task status is counted, rather than turned into completion. */
export type SharedBookProjectNotice = {
  schema:'yixu-shared-book-project-v1'; createdAt:number;
  omittedRuntimeTasks:number; omittedSupplyBodies:number;
  runtimeHistory:{kind:string;status:string;count:number}[];
  notice:string;
};

const retained = ['memories','chats','conversations','forgotten','transcriptRevisions',
  'readings','entityRoots','companionWorkspaces','publishedViews','viewPublications'] as const;
const runtimeCollections = ['agentSessions','tasks','readingDrafts','queryCheckpoints',
  'companionReadingReceipts','companionCorrectionRepairs','maintenanceJobs',
  'partnerMaintenanceCandidates'] as const;

function fail(field:string, reason:string):never {
  // Fields are generated by this module. Never echo source prose or values.
  throw Error('无法准备分享副本：'+field+' '+reason+'；原工程保持。');
}

function ownBookRecords(state:State, name:StateCollection, bookId:string):unknown[] {
  return ((state[name]??[]) as unknown[]).filter(value=>
    !!value&&typeof value==='object'&&(value as {bookId?:unknown}).bookId===bookId);
}

/** Reject sensitive literals instead of rewriting an author's or reader's text.
 * Configuration is removed at its known structural fields before this check. */
function inspect(value:unknown, field:string, bookId:string, sourceBooks:Set<string>, serviceUrls:readonly string[]):void {
  if(typeof value==='string') {
    if(/(?:[a-z]:[\\/]|\\\\[^\\\s]+\\|file:\/\/|(?:^|[\s"'])\/(?:Users|home|tmp|var|mnt|Volumes)\/)/i.test(value))
      fail(field,'包含本机绝对路径，不能在保留原话的同时自动脱敏');
    if(serviceUrls.some(url=>url&&value.includes(url))) fail(field,'包含来源模型服务地址');
    return;
  }
  if(!value||typeof value!=='object')return;
  if(Array.isArray(value)){value.forEach((item,index)=>inspect(item,field+'['+index+']',bookId,sourceBooks,serviceUrls));return;}
  for(const [key,item] of Object.entries(value)) {
    if(['apiKey','authorization','secrets','secretRef','modelService','baseUrl','native','materialRef'].includes(key))
      fail(field+'.'+key,'仍含运行配置或执行材料');
    if((key==='bookId'||key==='sourceBookId')&&typeof item==='string'&&item!==bookId)
      fail(field+'.'+key,'依赖其他书籍的实际记录');
    // A hidden reference in a JSON request key cannot import another book.
    if(key==='requestKey'&&typeof item==='string')try {
      const identity=JSON.parse(item);if(Array.isArray(identity)&&sourceBooks.has(identity[0])&&identity[0]!==bookId)
        fail(field+'.requestKey','依赖其他书籍的任务');
    } catch(error) {if(error instanceof Error&&error.message.startsWith('无法准备分享副本'))throw error;}
    inspect(item,field+'.'+key,bookId,sourceBooks,serviceUrls);
  }
}

function explicitSources(audit:FormationSources, state:State):FormationSources {
  validateFormationSources(audit,state);
  // materialRef is optional in the domain schema. Retain the exact flattened
  // attribution and evidence; an absent private supply body is disclosed below.
  const {materialRef:_,...sources}=audit;
  return sources;
}

/** Creates a new SQLite file; it never opens or replaces an existing destination.
 * Caller owns the surrounding project identity/folder and must hold its normal
 * save/pause boundary while capturing the source. No native runtime is consulted. */
export async function createSharedBookProject(source:NodeStore,targetFile:string,bookId:string):Promise<{bookId:string;title:string;omittedRuntimeTasks:number}> {
  try{return await prepareSharedBookProject(source,targetFile,bookId);}
  catch(error) {
    if(error instanceof Error&&error.message.startsWith('无法准备分享副本：'))throw error;
    // Native filesystem/SQLite errors may include the source's absolute path.
    // This public boundary deliberately does not forward those messages/causes.
    throw Error('无法准备分享副本：资料完整性或文件操作未通过核对；原工程保持。');
  }
}

async function prepareSharedBookProject(source:NodeStore,targetFile:string,bookId:string):Promise<{bookId:string;title:string;omittedRuntimeTasks:number}> {
  const targetPath=resolve(targetFile);
  if(targetPath===resolve(source.filename))fail('targetFile','不能覆盖原工程');
  try{await lstat(targetPath);fail('targetFile','目标文件已存在');}
  catch(error){if((error as NodeJS.ErrnoException).code!=='ENOENT')throw error;}

  const original=await source.load();
  if(!original)fail('source','没有已保存的阅读资料');
  const sourceBook=original.books.find(book=>book.id===bookId);
  if(!sourceBook)fail('bookId','所选书籍不存在');
  const book=structuredClone(sourceBook);
  book.text=await source.readBookText(book.version);
  delete book.residentRanges;delete book.readingSourceId;
  if(book.sourceFile)book.sourceFile={name:basename(book.sourceFile.name.replaceAll('\\','/'))};

  const defaults=initialState();
  const state:State={schema:1,publicationTrackingStartedAt:original.publicationTrackingStartedAt,
    books:[book],memories:[],chats:[],conversations:[],partners:[],partnerId:original.partnerId,
    usage:[],forgotten:[],settings:{...defaults.settings,services:[],serviceId:'',
      searchEndpoint:'',searchSecretRef:'',language:original.settings.language}};
  const records=state as unknown as Record<string,unknown>;
  for(const name of retained)records[name]=structuredClone(ownBookRecords(original,name,bookId));
  await hydrateMemoryBodies(source,state.memories);

  const partnerIds=new Set<string>([original.partnerId]);
  const findPartners=(value:unknown):void=>{
    if(!value||typeof value!=='object')return;
    if(Array.isArray(value)){value.forEach(findPartners);return;}
    for(const [key,item] of Object.entries(value)) {
      if(key==='partnerId'&&typeof item==='string')partnerIds.add(item);
      else findPartners(item);
    }
  };
  for(const name of retained)findPartners(state[name]);
  findPartners(book);
  state.partners=structuredClone(original.partners.filter(partner=>partnerIds.has(partner.id)));
  for(const partner of state.partners){delete partner.modelService;partner.backgroundBooks=partner.backgroundBooks.filter(id=>id===bookId);}
  state.partnerPersonaVersions=structuredClone((original.partnerPersonaVersions??[]).filter(item=>partnerIds.has(item.partnerId)));
  state.partnerThemes=structuredClone((original.partnerThemes??[]).filter(item=>partnerIds.has(item.partnerId)));
  state.habits=structuredClone((original.habits??[]).filter(habit=>partnerIds.has(habit.partnerId)&&(!habit.sourceBookId||habit.sourceBookId===bookId)));
  for(const conversation of state.conversations)delete conversation.context;
  for(const chat of state.chats) {
    // Published text stays exact; private parser/raw response carriers do not.
    delete chat.readingReaction;
    if(chat.publication)delete chat.publication.scene;
  }
  let omittedSupplyBodies=0;
  for(const record of [...state.memories,...(state.publishedViews??[])])if(record.formationSources) {
    if(record.formationSources.materialRef)omittedSupplyBodies++;
    record.formationSources=explicitSources(record.formationSources,state);
  }
  // bodyRef authenticates the unchanged prose and is regenerated by NodeStore.
  const identities=state.memories.map(memory=>({id:memory.id,hash:memory.bodyRef?.hash,text:memory.text}));

  const statuses=new Map<string,{kind:string;status:string;count:number}>();
  let omittedRuntimeTasks=0;
  for(const kind of runtimeCollections)for(const item of ownBookRecords(original,kind,bookId)) {
    const row=item as {status?:string;association?:string};
    const status=row.status??row.association??'saved',key=kind+':'+status;
    const entry=statuses.get(key)??{kind,status,count:0};entry.count++;statuses.set(key,entry);omittedRuntimeTasks++;
  }
  const taskIds=new Set(runtimeCollections.flatMap(kind=>ownBookRecords(original,kind,bookId))
    .flatMap(item=>typeof (item as {id?:unknown}).id==='string'?[(item as {id:string}).id]:[]));
  const chatIds=new Set(state.chats.map(chat=>chat.id));
  for(const usage of original.usage) {
    let belongs=!!usage.questionId&&chatIds.has(usage.questionId)||!!usage.agentSessionId&&taskIds.has(usage.agentSessionId)||
      !!usage.taskId&&taskIds.has(usage.taskId);
    if(usage.requestKey)try{const identity=JSON.parse(usage.requestKey);if(Array.isArray(identity)&&identity[0]===bookId)belongs=true;}catch{/* Unowned requests are not imported. */}
    if(!belongs)continue;
    const key='requests:'+usage.status,entry=statuses.get(key)??{kind:'requests',status:usage.status,count:0};
    entry.count++;statuses.set(key,entry);
  }
  const notice:SharedBookProjectNotice={schema:'yixu-shared-book-project-v1',createdAt:Date.now(),
    omittedRuntimeTasks,omittedSupplyBodies,runtimeHistory:[...statuses.values()],
    notice:'此副本保留本书原文、读点、已保存的认识与原话及明确来源。模型服务、费用账本、原生执行记录和运行供材全文未携带；未完成任务仍留在原工程，不会由此副本自动重发。'};
  (state as State&{sharedBookProject:SharedBookProjectNotice}).sharedBookProject=notice;

  const urls=[...original.settings.services,...original.partners.flatMap(partner=>partner.modelService?[partner.modelService]:[])].map(service=>service.baseUrl).filter(Boolean);
  // Stored memory bodies use bodyRef, which is intentionally not a task ref.
  inspect(state,'state',bookId,new Set(original.books.map(item=>item.id)),urls);

  const metadata=await source.loadObservations<ObservationMetadata>();
  const drafts:NonNullable<ObservationMetadata['drafts']>={};
  for(const [key,value] of Object.entries(metadata?.drafts??{})) {
    let identity:unknown;try{identity=JSON.parse(key);}catch{continue;}
    if(!Array.isArray(identity)||identity[1]!==bookId)continue;
    validateWorkbenchDraft(state,key,value);inspect(value,'drafts',bookId,new Set(original.books.map(item=>item.id)),urls);drafts[key]=structuredClone(value);
  }
  const observations:ObservationMetadata={observations:{events:[],ratings:{},timings:{},questions:{},readyDomains:{}},
    selectedBookId:bookId,pagePosition:metadata?.selectedBookId===bookId?metadata.pagePosition:Math.max(0,book.position-1),
    pageChars:metadata?.pageChars??1600,drafts,importedHistory:notice.notice};

  // Existing domain validators run against a detached copy with temporary
  // built-in defaults. Those defaults are never written into the share file.
  const validation=structuredClone(state);validation.settings=structuredClone(defaults.settings);
  const empty=initialState();empty.partners=[];empty.partnerPersonaVersions=[];
  await restoreBackupState(validation,empty,source);

  const pending=targetPath+'.'+randomUUID()+'.pending';
  let output:NodeStore|undefined,claimed=false;
  try {
    output=new NodeStore(pending);
    for(const partner of state.partners)if(partner.avatar?.kind==='image') {
      const avatar=await source.readPartnerAvatar(partner.avatar.assetId);
      if(!avatar)fail('partners.avatar','缺少头像原件');
      await output.writePartnerAvatar(avatar);
    }
    await output.save(state);await output.saveObservations(observations);await output.flush();
    const check=await output.load();if(!check||check.books.length!==1||check.books[0].id!==bookId)fail('output','书籍身份核对失败');
    await hydrateMemoryBodies(output,check.memories);
    for(const identity of identities) {
      const memory=check.memories.find(item=>item.id===identity.id);
      if(!memory||memory.text!==identity.text||identity.hash&&memory.bodyRef?.hash!==identity.hash)fail('memories','正文或身份核对失败');
    }
    await output.close();output=undefined;
    // Reserve the final name atomically. A racing existing file is not replaced.
    const reservation=await open(targetPath,'wx',0o600);await reservation.close();claimed=true;
    await rename(pending,targetPath);claimed=false;
    return{bookId,title:book.title,omittedRuntimeTasks};
  } finally {
    await output?.close();
    if(claimed)await rm(targetPath,{force:true});
    await rm(pending,{force:true});await rm(pending+'-wal',{force:true});await rm(pending+'-shm',{force:true});
  }
}
